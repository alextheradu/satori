assert.equal(key('Solve $-3(x-4)^2=0$.'),key('Solve $x^2-8x+16=0$.'))
assert.equal(key('Solve $2x^{2}-4x=0$.'),key('Solve $x^2-2x+0=0$.'))
assert.equal(key('Solve $6+2x^2-8x=0$.'),key('Solve $(x-1)(x-3)=0$.'))
assert.equal(key('Solve $-(x+2)(x-2)=0$.'),key('Solve $x^2-4=0$.'))
assert.equal(key('Solve  $2x + 1=3$.'),key('Solve $2x+1 = 3$.'))
assert.notEqual(key('Solve $2x^2+3x+1=0$.'),key('Solve $2x^2+6x+2=0$.'))
assert.notEqual(key('Solve $(2x-3)(3x+7)=0$.'),key('Solve $6x^2-5x-21=0$.'))
assert.notEqual(key('Solve $(x-2)(y+2)=0$.'),key('Solve $x^2-4=0$.'))
assert.notEqual(key('Solve $0(x-2)(x+2)=0$.'),key('Solve $x^2-4=0$.'))

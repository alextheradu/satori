import assert from 'node:assert/strict'
import {questionFingerprint} from './question-fingerprint.mjs'
const key=prompt=>questionFingerprint({prompt})
assert.equal(key('The roots of $3x^2-90x+627=0$ are r and s. Find their sum.'),key('The roots of $7x^2-210x+1463=0$ are r and s. Find their sum.'))
assert.equal(key('Solve $-3x^2+90x-627=0$.'),key('Solve $x^2-30x+209=0$.'))

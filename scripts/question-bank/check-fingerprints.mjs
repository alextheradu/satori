assert.notEqual(key('Solve $x^2-4=1$.'),key('Solve $x^2-4=0$.'))
assert.notEqual(key('Solve $x^2-4<0$.'),key('Solve $x^2-4=0$.'))
assert.notEqual(key('Solve $x^2+9007199254740993-9007199254740992=0$.'),key('Solve $x^2=0$.'))
assert.notEqual(key('For $a=2$ and $A=3$, find $a$.'),key('For $a=2$ and $A=3$, find $A$.'))
assert.notEqual(key('What does Polish mean?'),key('What does polish mean?'))
assert.notEqual(key('The roots of $x^2-30x+209=0$ are r and s. Find their sum.'),key('The roots of $x^2-30x+209=0$ are r and s. Find their product.'))
assert.notEqual(key('A price of \\$20 increases by $5\\%$.'),key('A price of \\$25 increases by $5\\%$.'))
